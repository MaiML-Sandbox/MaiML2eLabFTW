from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Any


class ErrorCode(StrEnum):
    INVALID_SOURCE_TYPE = "INVALID_SOURCE_TYPE"
    INVALID_XML = "INVALID_XML"
    MISSING_DOCUMENT_UUID = "MISSING_DOCUMENT_UUID"
    MISSING_METHOD_UUID = "MISSING_METHOD_UUID"
    DUPLICATE_ID = "DUPLICATE_ID"
    BROKEN_REFERENCE = "BROKEN_REFERENCE"
    INVALID_PNML = "INVALID_PNML"
    AMBIGUOUS_STEP_ORDER = "AMBIGUOUS_STEP_ORDER"
    PNML_CYCLE = "PNML_CYCLE"
    MISSING_INSTRUCTION = "MISSING_INSTRUCTION"
    AMBIGUOUS_INSTRUCTION_ORDER = "AMBIGUOUS_INSTRUCTION_ORDER"
    INVALID_ORDER_FILE = "INVALID_ORDER_FILE"
    ORDER_SOURCE_MISMATCH = "ORDER_SOURCE_MISMATCH"
    UNSUPPORTED_FIELD_TYPE = "UNSUPPORTED_FIELD_TYPE"
    UNRESOLVED_INSERTION = "UNRESOLVED_INSERTION"
    MISSING_SOURCE_ATTACHMENT = "MISSING_SOURCE_ATTACHMENT"
    INVALID_TEMPLATE_PLAN = "INVALID_TEMPLATE_PLAN"
    DUPLICATE_SOURCE = "DUPLICATE_SOURCE"
    API_WRITE_FAILED = "API_WRITE_FAILED"
    ROLLBACK_FAILED = "ROLLBACK_FAILED"
    INVALID_TEMPLATE_CONTRACT = "INVALID_TEMPLATE_CONTRACT"


@dataclass(frozen=True)
class ConversionError(Exception):
    code: ErrorCode
    message: str
    details: dict[str, Any] | None = None

    def __str__(self) -> str:
        return f"{self.code}: {self.message}"
